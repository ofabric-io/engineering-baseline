#!/usr/bin/env node
// Keeps AI-tool adapters in sync with the canonical .agents/ content.
//   node scripts/sync-adapters.mjs          write adapters
//   node scripts/sync-adapters.mjs --check  verify only (exit 1 on drift)
//
// Canonical: AGENTS.md and .agents/skills/<name>/SKILL.md.
// Generated: the skills index in AGENTS.md, and .claude/skills/<name>/SKILL.md pointer stubs.
// Every project ships a pointer for each supported tool, so any AI tool works without setup.
// Codex and other AGENTS.md-native tools need no pointer; AGENTS.md lists every skill by path.
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, read, frontmatter } from './lib.mjs';

const CHECK = process.argv.includes('--check');
const problems = [];

// Pointer files: must stay small and must point at AGENTS.md.
const POINTERS = ['CLAUDE.md', 'GEMINI.md', '.github/copilot-instructions.md', '.cursor/rules/agents.mdc'];
const MAX_POINTER_LINES = 15;
for (const p of POINTERS) {
  const abs = join(ROOT, p);
  if (!existsSync(abs)) { problems.push(`${p}: adapter is missing; every supported AI tool gets a pointer to AGENTS.md`); continue; }
  const text = read(abs);
  if (!text.includes('AGENTS.md')) problems.push(`${p}: an adapter must point to AGENTS.md`);
  if (text.trim().split('\n').length > MAX_POINTER_LINES) {
    problems.push(`${p}: an adapter holds at most ${MAX_POINTER_LINES} lines; move rules into AGENTS.md or docs/`);
  }
}

// Tool-hook adapters hold wiring only: every hook command must call a script in scripts/guards/.
const settingsPath = join(ROOT, '.claude', 'settings.json');
if (existsSync(settingsPath)) {
  try {
    const hooks = Object.values(JSON.parse(read(settingsPath)).hooks ?? {}).flat().flatMap((h) => h.hooks ?? []);
    for (const h of hooks) {
      if (!/^node\s+"?[^\s"]*scripts\/guards\/[\w.-]+\.mjs"?(\s+\S+)*$/.test(h.command ?? '')) {
        problems.push(`.claude/settings.json: hook "${h.command}" must only run "node scripts/guards/<name>.mjs"; put logic in scripts/guards/, not in the adapter`);
      }
    }
  } catch {
    problems.push('.claude/settings.json: not valid JSON');
  }
}

// Canonical skills.
const skillsDir = join(ROOT, '.agents', 'skills');
const skills = existsSync(skillsDir)
  ? readdirSync(skillsDir, { withFileTypes: true })
      .filter((d) => d.isDirectory() && existsSync(join(skillsDir, d.name, 'SKILL.md')))
      .map((d) => {
        const fm = frontmatter(read(join(skillsDir, d.name, 'SKILL.md'))) ?? {};
        if (fm.name !== d.name) problems.push(`.agents/skills/${d.name}/SKILL.md: frontmatter name must be "${d.name}"`);
        if (!fm.description) problems.push(`.agents/skills/${d.name}/SKILL.md: missing description`);
        return { name: d.name, description: fm.description ?? '' };
      })
      .sort((a, b) => a.name.localeCompare(b.name))
  : [];

function expect(path, content) {
  const abs = join(ROOT, path);
  const current = existsSync(abs) ? read(abs) : null;
  if (current === content) return;
  if (CHECK) problems.push(`${path}: out of date — run node scripts/sync-adapters.mjs`);
  else {
    mkdirSync(join(abs, '..'), { recursive: true });
    writeFileSync(abs, content);
    console.log(`wrote ${path}`);
  }
}

// 1. Skills index in AGENTS.md.
const agentsPath = join(ROOT, 'AGENTS.md');
if (existsSync(agentsPath)) {
  const agents = read(agentsPath);
  const START = /<!-- skills-index:start[^>]*-->/;
  const END = '<!-- skills-index:end -->';
  const s = agents.match(START);
  const e = agents.indexOf(END);
  if (!s || e < 0) problems.push('AGENTS.md: skills-index markers are missing');
  else {
    const index = skills.map((k) => `- **${k.name}** — \`.agents/skills/${k.name}/SKILL.md\``).join('\n');
    const next = agents.slice(0, s.index + s[0].length) + '\n' + index + '\n' + agents.slice(e);
    expect('AGENTS.md', next);
  }
}

// 2. Claude Code skill pointers.
{
  for (const k of skills) {
    const desc = k.description.includes(':') || k.description.includes('"')
      ? JSON.stringify(k.description) : k.description;
    expect(`.claude/skills/${k.name}/SKILL.md`,
      `---\nname: ${k.name}\ndescription: ${desc}\n---\n\n` +
      `<!-- Generated by scripts/sync-adapters.mjs. Edit .agents/skills/${k.name}/SKILL.md instead. -->\n\n` +
      `Read \`.agents/skills/${k.name}/SKILL.md\` and follow it exactly.\n`);
  }
  const stubDir = join(ROOT, '.claude', 'skills');
  if (existsSync(stubDir)) {
    for (const d of readdirSync(stubDir)) {
      if (skills.some((k) => k.name === d)) continue;
      if (CHECK) problems.push(`.claude/skills/${d}: no canonical skill — run node scripts/sync-adapters.mjs`);
      else { rmSync(join(stubDir, d), { recursive: true }); console.log(`removed .claude/skills/${d}`); }
    }
  }
}

if (problems.length) {
  for (const p of problems) console.log(p);
  process.exit(1);
}
if (!CHECK) console.log('adapters: in sync');
