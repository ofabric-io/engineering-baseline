#!/usr/bin/env node
// Regenerates the "Enforcement debt" table in docs/DECISION-QUEUE.md from every `⬜` row in the
// `## Enforcement` tables of proposed, in-progress and ratified standards.
//   node scripts/queue.mjs           rewrite the table between the markers
//   node scripts/queue.mjs --check   exit 1 (one "path: message" line) if the table is stale
//
// The table lives between `<!-- debt:start -->` and `<!-- debt:end -->`. A block that was never
// generated (no generated-by line yet) is skipped by --check until the first run of this script.
// Due: a row says when it falls due with one of the words below anywhere in its Mechanism or
// Status cell (for example `⬜ before-production`); a row that says nothing is `when-stack-decided`.
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { ROOT, walk, rel, read, frontmatter, enforcementRows, isTemplatePath } from './lib.mjs';

export const DUE = ['before-first-release', 'before-production', 'when-stack-decided', 'later'];
const START = '<!-- debt:start -->';
const END = '<!-- debt:end -->';
const GENERATED = '<!-- generated by scripts/queue.mjs: edit the Enforcement tables, then re-run it -->';
const QUEUE = join(ROOT, 'docs', 'DECISION-QUEUE.md');

const docs = walk(join(ROOT, 'docs'), (p) => p.endsWith('.md')).filter((p) => !isTemplatePath(rel(p)));
const byBase = new Map();
for (const p of docs) byBase.set(p.split(/[\\/]/).pop(), [...(byBase.get(p.split(/[\\/]/).pop()) ?? []), p]);
const docsRel = (abs) => rel(abs).replace(/^docs\//, '');

/** Resolves a document reference found in `from` to an absolute path, or null. */
function resolveDoc(ref, from) {
  const p = ref.replace(/^\.\//, '');
  const tries = [resolve(dirname(from), p), join(ROOT, 'docs', p), join(ROOT, p)];
  const hit = tries.find((c) => existsSync(c) && c.startsWith(join(ROOT, 'docs')));
  if (hit) return hit;
  const same = p.includes('/') ? [] : byBase.get(p) ?? [];
  return same.length === 1 ? same[0] : null;
}

/** Rewrites document references in a cell to docs/-relative paths. */
function rewrite(text, from) {
  const fix = (ref) => { const abs = resolveDoc(ref.split('#')[0], from); return abs ? docsRel(abs) : null; };
  return text
    .replace(/\[([^\]]*)\]\(([^)\s]+\.md)(#[^)]*)?\)/g, (m, t, ref) => (fix(ref) ? `\`${fix(ref)}\`` : m))
    .replace(/`([^`\s]+\.md)`/g, (m, ref) => (fix(ref) ? `\`${fix(ref)}\`` : m));
}

const dueOf = (cells) => DUE.find((d) => cells.join(' ').includes(d)) ?? 'when-stack-decided';
const ruleNo = (s) => Number((s.match(/\d+/) ?? [0])[0]);

function debtRows() {
  const out = [];
  for (const abs of docs) {
    const text = read(abs);
    const fm = frontmatter(text);
    if (!fm || !['proposed', 'in-progress', 'ratified'].includes(fm.status) || 'spec' in fm || 'story' in fm) continue;
    if (/^docs\/04-adr\/ADR-\d+/.test(rel(abs))) continue;
    for (const row of enforcementRows(text)) {
      if (row.status !== '⬜') continue;
      const rule = row.cells[0].replace(/[*`]/g, '').trim();
      const mechanism = rewrite(row.cells.slice(1, -1).join(' / ').replace(/[⬜✅◐❌]/g, '').trim() || '—', abs);
      out.push({ doc: docsRel(abs), rule, mechanism, due: dueOf(row.cells.slice(1)) });
    }
  }
  return out.sort((a, b) => a.doc.localeCompare(b.doc) || ruleNo(a.rule) - ruleNo(b.rule));
}

export function table(rows) {
  const head = ['| Document | Rule | Mechanism | Due |', '| --- | --- | --- | --- |'];
  const body = rows.map((r) => `| \`${r.doc}\` | ${r.rule} | ${r.mechanism} | ${r.due} |`);
  return [GENERATED, '', ...head, ...body].join('\n');
}

const norm = (s) => s.split('\n').map((l) => l.trimEnd()).join('\n').trim();

function main() {
  const check = process.argv.includes('--check');
  const rows = debtRows();
  const fresh = table(rows);
  const file = 'docs/DECISION-QUEUE.md';
  const text = existsSync(QUEUE) ? read(QUEUE) : '';
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a === -1 || b === -1 || b < a) {
    if (check) { console.error(`queue: ${file} has no ${START} / ${END} markers; skipped`); return; }
    console.error(`queue: ${file} has no ${START} / ${END} markers around the debt table; printing the table instead. Add both markers, then re-run.`);
    console.log(fresh);
    return;
  }
  const block = text.slice(a + START.length, b);
  if (check) {
    if (!block.includes('generated by scripts/queue.mjs')) return; // never generated yet
    if (norm(block) !== norm(fresh)) {
      console.log(`${file}: the enforcement-debt table is stale; run "node scripts/queue.mjs" and commit the result`);
      process.exit(1);
    }
    return;
  }
  const next = `${text.slice(0, a + START.length)}\n${fresh}\n${text.slice(b)}`;
  if (next !== text) writeFileSync(QUEUE, next);
  console.log(`queue: ${rows.length} enforcement-debt row(s) written to ${file}`);
}

main();
