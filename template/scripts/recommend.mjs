#!/usr/bin/env node
// Builds the bootstrap's recommendation sheet: one row per open decision, so the brief (0.1) can
// be turned into a recommended answer for each, and the user can accept them all at once.
//   node scripts/recommend.mjs          write or merge .baseline/recommendations.md
//   node scripts/recommend.mjs --check  fail if the sheet is missing rows or a row is incomplete
//   node scripts/recommend.mjs --json   print the rows as JSON (with `answered` per row)
//   --kinds cli,library                 the project's component kinds, when the Components table and
//                                       answers.yaml do not have them yet; marks rows n/a
// What counts as a decision, and its id, is defined in scripts/decisions.mjs. Re-running keeps
// every filled row, adds new ones, and shows a row answered in .baseline/answers.yaml as `user`
// when it was still `ask`. Exit 1 when the questionnaire names a document or parameter that does
// not exist, or when a document with open parameters or decisions is offered by no question.
import { ROOT, read } from './lib.mjs';
import { existsSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { loadDecisions, cells, esc, phaseOf, SHEET, SOURCES, PHASES } from './decisions.mjs';

const args = process.argv.slice(2);
const kindsArg = args.includes('--kinds') ? args[args.indexOf('--kinds') + 1] ?? '' : '';
const { rows, errors } = loadDecisions({ kinds: kindsArg.split(',').map((k) => k.trim()).filter(Boolean) });
if (errors.length) {
  for (const e of errors) console.error(`recommend: ${e}`);
  process.exit(1);
}

if (args.includes('--json')) {
  console.log(JSON.stringify(rows, null, 2));
  process.exit(0);
}

const existing = new Map();
const sheetPath = join(ROOT, SHEET);
if (existsSync(sheetPath)) {
  for (const line of read(sheetPath).split(/\r?\n/)) {
    const c = cells(line);
    if (!c || c.length < 5 || c[0] === 'Id' || /^-+$/.test(c[0])) continue;
    existing.set(c[0], { recommended: c[2], source: c[3], why: c[4] });
  }
}

if (args.includes('--check')) {
  const problems = [];
  if (!existsSync(sheetPath)) problems.push(`${SHEET} does not exist; run node scripts/recommend.mjs`);
  for (const r of rows) {
    if (r.answered) continue; // answered in .baseline/answers.yaml: the sheet no longer decides it
    const s = existing.get(r.id);
    if (!s) { if (existsSync(sheetPath)) problems.push(`${r.id}: missing from the sheet; run node scripts/recommend.mjs to add it`); continue; }
    if (!SOURCES.includes(s.source)) problems.push(`${r.id}: Source "${s.source}" is not one of ${SOURCES.join(', ')}`);
    if (['brief', 'derived', 'default', 'user'].includes(s.source) && !s.recommended) problems.push(`${r.id}: Source is ${s.source} but Recommended is empty`);
    if (['brief', 'derived', 'n/a'].includes(s.source) && !s.why) problems.push(`${r.id}: Source is ${s.source} but Why is empty; quote the brief or name the answer it follows from`);
  }
  for (const p of problems) console.error(`recommend: ${p}`);
  const open = rows.filter((r) => !r.answered);
  const asks = open.filter((r) => existing.get(r.id)?.source === 'ask').length;
  if (!problems.length) console.log(`recommend: ok — ${open.length} open decision(s), ${asks} to ask, ${rows.length - open.length} answered`);
  process.exit(problems.length ? 1 : 0);
}

const merged = rows.map((r) => {
  const s = existing.get(r.id);
  // An untouched default row turns n/a once the kinds are known; anything filled in is kept.
  const untouched = s && r.plain && s.source === r.plain.source && s.recommended === r.plain.recommended && !s.why;
  const out = s && !untouched && (s.recommended || s.source !== r.source || s.why) ? { ...r, ...s } : { ...r };
  if (r.answered && (out.source === 'ask' || !out.recommended)) Object.assign(out, { source: 'user', recommended: r.answer });
  return out;
});
const dropped = [...existing.keys()].filter((id) => !rows.some((r) => r.id === id));

const out = [
  '# Recommendation sheet',
  '',
  'Generated by `node scripts/recommend.mjs` from `bootstrap/questionnaire.md`, every open',
  'parameter and every open decision in `docs/`. The bootstrap fills in **Recommended**, **Source**',
  'and **Why** from the brief (0.1), then asks once whether to accept every recommendation (0.6).',
  'Re-running the script keeps filled rows and adds new ones; `--check` fails while a row is',
  'incomplete.',
  '',
  'Source: `brief` — the brief settles it, and Why quotes the brief · `derived` — it follows from',
  'another answer, and Why names it · `default` — the baseline default; the brief says nothing',
  'against it · `ask` — there is no default, or the brief is silent on a ⚑ question; it is asked',
  'whatever mode is chosen · `n/a` — the component kinds make it moot, and Why says which ·',
  '`user` — the user answered it directly.',
  '',
  "An open decision's default is `later`: it is deferred to `docs/DECISION-QUEUE.md`, never",
  'guessed. Recommend a value only when the brief or another answer settles it.',
  '',
];
for (const [key, title] of PHASES) {
  const part = merged.filter((r) => phaseOf(r.id) === key);
  if (!part.length) continue;
  out.push(`## ${title}`, '', '| Id | Decision | Recommended | Source | Why |', '| --- | --- | --- | --- | --- |');
  for (const r of part) out.push(`| ${esc(r.id)} | ${esc(r.decision)} | ${esc(r.recommended)} | ${esc(r.source)} | ${esc(r.why)} |`);
  out.push('');
}
mkdirSync(dirname(sheetPath), { recursive: true });
writeFileSync(sheetPath, out.join('\n'));
const count = (s) => merged.filter((r) => r.source === s).length;
console.log(`recommend: wrote ${SHEET} — ${merged.length} decision(s): ${SOURCES.map((s) => `${count(s)} ${s}`).join(', ')}`);
if (dropped.length) console.log(`recommend: dropped rows no longer open: ${dropped.join(', ')}`);
